// Bridge for the app's own workshop manual viewer (manual/viewer.html). Only loaded into that page.
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('manual', {
  init: () => ipcRenderer.invoke('manual', 'init'),
  book: () => ipcRenderer.invoke('manual', 'book'),
  tree: () => ipcRenderer.invoke('manual', 'tree'),
  proc: (link) => ipcRenderer.invoke('manual', 'proc', link),
  oasis: () => ipcRenderer.invoke('manual', 'oasis'),
  cv: () => ipcRenderer.invoke('manual', 'cv'),
  tsbList: () => ipcRenderer.invoke('manual', 'tsb-list'),
  tsbArticle: (url) => ipcRenderer.invoke('manual', 'tsb-article', { url }),
  openTsb: (r) => ipcRenderer.invoke('manual', 'open-tsb', r),
  openArticle: (url, title) => ipcRenderer.invoke('manual', 'open-article', { url, title }),
  wiringToc: () => ipcRenderer.invoke('manual', 'wiring-toc'),
  wiringPages: (cell) => ipcRenderer.invoke('manual', 'wiring-pages', { cell }),
  wiringSvg: (cell, page) => ipcRenderer.invoke('manual', 'wiring-svg', { cell, page }),
  wiringLocations: (item) => ipcRenderer.invoke('manual', 'wiring-locations', { item }),
  wiringSearch: (text) => ipcRenderer.invoke('manual', 'wiring-search', { text }),
  wiringFord: (q) => ipcRenderer.invoke('manual', 'wiring-ford', q),
  openWiring: (q) => ipcRenderer.invoke('manual', 'open-wiring', q),
  slts: (req) => ipcRenderer.invoke('manual', 'slts', req),
  svcList: () => ipcRenderer.invoke('manual', 'svc-list'),
  svc: (fsa) => ipcRenderer.invoke('manual', 'svc', { fsa }),
  setDealerCode: (code) => ipcRenderer.invoke('manual', 'set-dealer-code', code),
  copy: (text) => ipcRenderer.invoke('manual', 'copy', text),
  spa: (q) => ipcRenderer.invoke('manual', 'spa', q),
  report: (ev) => ipcRenderer.invoke('manual', 'report', ev),
  signIn: () => ipcRenderer.invoke('manual', 'signin'),
  openPts: () => ipcRenderer.invoke('manual', 'open-pts'),
  openUrl: (url) => ipcRenderer.invoke('manual', 'open-url', url),
  openLog: () => ipcRenderer.invoke('manual', 'open-log'),
  log: (text) => ipcRenderer.invoke('manual', 'log', text),
  save: (state) => ipcRenderer.send('manual-save', state),
  onOpen: (fn) => ipcRenderer.on('manual-open', (_e, link) => fn(link)),
  diag: (q) => ipcRenderer.invoke('manual', 'diag', q),
  openProc: (link) => ipcRenderer.invoke('manual', 'open-proc', link),
  openDiag: (query) => ipcRenderer.invoke('manual', 'open-diag', query),
});
